// Generates public/demo/pdf-smart-synthetic-demo.pdf: an ORIGINAL synthetic practice
// paper written for PDF Smart. It is NOT a CTET/UGC NET paper and contains no content
// from any official paper. It deliberately exercises the parser: running header/footer,
// numbered instructions on a cover page, wrapped stems, two-per-line options, (1)-(4)
// and A-D labels, a passage block, a figure reference and one malformed question.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public', 'demo', 'pdf-smart-synthetic-demo.pdf');

const pdf = await PDFDocument.create();
pdf.setTitle('PDF Smart — Synthetic Practice Paper (original demo, not an official exam)');
pdf.setAuthor('PDF Smart demo generator');
pdf.setSubject('Original synthetic content for demonstrating extraction. Not a CTET or UGC NET paper.');
const font = await pdf.embedFont(StandardFonts.Helvetica);
const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

const W = 595;
const H = 842;
const M = 56;
const pages = [
  [
    { t: 'PDF Smart Synthetic Practice Paper', f: bold, s: 18 },
    { t: 'ORIGINAL DEMO CONTENT - NOT A CTET OR UGC NET PAPER', f: bold, s: 11 },
    { t: '' },
    { t: 'Instructions' , f: bold },
    { t: '1. This booklet is generated by PDF Smart for demonstration.' },
    { t: '2. It contains 12 multiple-choice questions.' },
    { t: '3. No answer key is printed in this booklet.' },
    { t: '4. Answer keys can be entered or imported in the app.' },
    { t: '5. Question 12 is intentionally incomplete to show review warnings.' },
    { t: '6. Use the original-page view to compare extraction.' },
  ],
  [
    { t: 'PART - I', f: bold },
    { t: 'Direction : Answer the following questions (Q. Nos 1 to 6) by selecting the most appropriate option.' },
    { t: '1. A learner who remembers best after building a model is most likely' },
    { t: '   showing which preference?' },
    { t: '(1) Listening                        (2) Reading' },
    { t: '(3) Hands-on activity                (4) Copying notes' },
    { t: '2. Which practice gives a teacher the most useful ongoing information' },
    { t: '   about how children are learning?' },
    { t: '(1) A single end-of-year test' },
    { t: '(2) Regular observation and short conversations' },
    { t: '(3) Ranking the class by marks' },
    { t: '(4) Checking attendance only' },
    { t: '3. Mistakes made by children while learning are best treated as' },
    { t: '(1) signs of laziness              (2) windows into their thinking' },
    { t: '(3) reasons for punishment         (4) things to ignore' },
    { t: '4. Which of the following best describes a "rubric"?' },
    { t: 'A. A list of school rules' },
    { t: 'B. A set of criteria describing levels of quality' },
    { t: 'C. A timetable for examinations' },
    { t: 'D. A type of seating plan' },
  ],
  [
    { t: '5. Consider the statements: (a) Play can support language growth.' },
    { t: '   (b) Group work never helps shy children.' },
    { t: '(1) Only (a) is correct            (2) Only (b) is correct' },
    { t: '(3) Both (a) and (b) are correct   (4) Neither is correct' },
    { t: '6. Study the figure shown below and choose the shape with the most sides.' },
    { t: '(1) Triangle   (2) Square   (3) Pentagon   (4) Hexagon' },
    { t: 'Directions: Read the passage below and answer the questions that follow (Q. Nos 7 to 9).' },
    { t: 'The village library opened on a rainy Monday. At first only three children came, sitting' },
    { t: 'close to the window where the light was best. By the end of the month the room was full,' },
    { t: 'and the librarian had started a reading circle where older children read aloud to younger ones.' },
    { t: '7. On which day did the library open?' },
    { t: '(1) Sunday   (2) Monday   (3) Friday   (4) Saturday' },
    { t: '8. Why did the first children sit near the window?' },
    { t: '(1) It was warmer      (2) The light was best' },
    { t: '(3) It was quieter     (4) They could see the rain' },
  ],
  [
    { t: '9. The reading circle mainly involved' },
    { t: '(1) teachers testing children     (2) older children reading to younger ones' },
    { t: '(3) parents buying books          (4) children writing stories' },
    { t: '10. Which number is the smallest?' },
    { t: '(1) 0.5   (2) 0.05   (3) 0.55   (4) 5' },
    { t: '11. A rectangle is 8 cm long and 3 cm wide. What is its perimeter?' },
    { t: '(1) 11 cm   (2) 22 cm   (3) 24 cm   (4) 16 cm' },
    { t: '12. This question is intentionally incomplete and has only two options.' },
    { t: '(1) First option' },
    { t: '(2) Second option' },
  ],
];

pages.forEach((lines, i) => {
  const page = pdf.addPage([W, H]);
  page.drawText('PDF Smart Synthetic Practice Paper - original demo content', { x: M, y: H - 32, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
  let y = H - 72;
  for (const l of lines) {
    const size = l.s ?? 11;
    if (l.t) page.drawText(l.t, { x: M, y, size, font: l.f ?? font, color: rgb(0.1, 0.1, 0.1) });
    y -= size * 1.6;
  }
  page.drawText(`DEMO-SYN   ${i + 1}   PDF Smart`, { x: M, y: 30, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
});

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, await pdf.save());
console.log(`Wrote ${out}`);
