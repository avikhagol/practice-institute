test('missing language assets disable OCR with a recoverable message',async({page})=>{
 await login(page);await page.getByRole('button',{name:'Sources',exact:true}).click();
 // Clear this browser cache then simulate a genuinely missing server asset.
 await page.evaluate(async()=>{for(const name of await caches.keys())await caches.delete(name);});
 await page.route('**/lang-data/*.traineddata.gz',route=>route.fulfill({status:404,body:'missing'}));
 await page.getByRole('button',{name:'Run OCR scan'}).first().click();
 const dialog=page.getByRole('dialog');await expect(dialog.getByText(/Language assets unavailable/)).toBeVisible();
 await expect(dialog.getByRole('button',{name:'Start OCR extraction'})).toBeDisabled();
 await dialog.getByRole('button',{name:'Close',exact:true}).click();
});

test('checksum failure and cancellation during language download are recoverable',async({page})=>{
 await login(page);await page.getByRole('button',{name:'Sources',exact:true}).click();
 await page.evaluate(async()=>{for(const name of await caches.keys())await caches.delete(name);});
 const row=page.getByRole('row').filter({hasText:'OCR synthetic desktop'});
 await page.route('**/lang-data/*.traineddata.gz',route=>route.request().method()==='HEAD'?route.continue():route.fulfill({status:200,contentType:'application/gzip',body:Buffer.from([31,139,0,1])}));
 await row.getByRole('button',{name:'Run OCR scan'}).click();const dialog=page.getByRole('dialog');
 await dialog.getByRole('button',{name:'Start OCR extraction'}).click();
 await expect(dialog.getByRole('alert')).toContainText('checksum failed');
 await expect(dialog.getByRole('button',{name:'Start OCR extraction'})).toBeVisible();
 await dialog.getByRole('button',{name:'Close',exact:true}).click();await page.unroute('**/lang-data/*.traineddata.gz');
 await page.route('**/lang-data/*.traineddata.gz',async route=>{if(route.request().method()==='HEAD')await route.continue();else{await new Promise(r=>setTimeout(r,2000));await route.continue().catch(()=>{});}});
 await row.getByRole('button',{name:'Run OCR scan'}).click();await dialog.getByRole('button',{name:'Start OCR extraction'}).click();
 await expect(dialog.getByRole('status')).toContainText('Downloading');
 await dialog.getByRole('button',{name:'Cancel OCR job'}).click();
 await expect(dialog.getByRole('alert')).toContainText(/cancel|abort/i);await dialog.getByRole('button',{name:'Close',exact:true}).click();
});
